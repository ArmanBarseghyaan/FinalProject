package com.seabattle.model;

/**
 * Результат выстрела по клетке игрового поля.
 */
public enum ShotResult {
    MISS,          // Промах
    HIT,           // Попадание (корабль ранен)
    SUNK,          // Попадание, приводящее к полному затоплению корабля
    ALREADY_SHOT   // В эту клетку уже стреляли ранее
}
